local function set(groups)
  for name, spec in pairs(groups) do
    vim.api.nvim_set_hl(0, name, spec)
  end
end

local function link(groups)
  for name, target in pairs(groups) do
    vim.api.nvim_set_hl(0, name, { link = target, default = false })
  end
end

